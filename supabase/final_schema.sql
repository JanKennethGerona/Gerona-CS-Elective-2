-- 3a. handle_new_user  (from Supabase_Setup.pdf)
--     Every new account starts as a CUSTOMER.
--     Extended with coalesce() so Google sign-ups (which send
--     full_name / given_name instead of firstname / lastname) also get names.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data->>'firstname',
      new.raw_user_meta_data->>'given_name',
      split_part(coalesce(new.raw_user_meta_data->>'full_name',
                          new.raw_user_meta_data->>'name', ''), ' ', 1)
    ),
    coalesce(
      new.raw_user_meta_data->>'lastname',
      new.raw_user_meta_data->>'family_name',
      nullif(regexp_replace(coalesce(new.raw_user_meta_data->>'full_name',
                                     new.raw_user_meta_data->>'name', ''),
                            '^\S+\s*', ''), '')
    ),
    (select id from public.roles where role = 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

-- 3b. is_admin  (from Supabase_Setup.pdf)
--     SECURITY DEFINER so it can read profiles/roles without being
--     blocked by (or recursing into) the RLS policies that call it.
create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
end;
$$;

-- 3c. protect_profile_role
--     Users can update their own profile, but NEVER their role.
--     (Requests from the app always have auth.uid(); the SQL Editor does not,
--     so the project owner can still promote an admin from the dashboard.)
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null then
    if new.role_id is distinct from old.role_id then
      raise exception 'You are not allowed to change a role'
        using errcode = '42501';
    end if;
    if new.id <> old.id
       or new.email is distinct from old.email
       or new.created_at <> old.created_at then
      raise exception 'Only first name and last name can be changed'
        using errcode = '42501';
    end if;
  end if;
  return new;
end;
$$;

-- 3d. place_order  (checkout RPC – atomic)
--     The app sends ONLY product ids and quantities:
--       [{"product_id": 3, "quantity": 2}, ...]
--     Names, prices and stock are read from the database here.
--     Everything runs in one transaction: if anything fails, nothing is saved.
create or replace function public.place_order(items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user      uuid    := auth.uid();
  v_order_id  bigint;
  v_total     numeric := 0;
  v_price     numeric;
  v_item      record;
  v_product   record;
begin
  if v_user is null then
    raise exception 'You must be signed in to place an order' using errcode = '42501';
  end if;

  if public.is_admin() then
    raise exception 'Admins cannot place orders' using errcode = '42501';
  end if;

  if items is null or jsonb_typeof(items) <> 'array' or jsonb_array_length(items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  insert into public.orders (user_id, status, total)
  values (v_user, 'pending', 0)
  returning id into v_order_id;

  -- merge duplicate lines, lock rows in a stable order (avoids deadlocks)
  for v_item in
    select (e->>'product_id')::bigint     as product_id,
           sum((e->>'quantity')::bigint)  as quantity
    from jsonb_array_elements(items) as e
    group by 1
    order by 1
  loop
    if v_item.product_id is null or v_item.quantity is null or v_item.quantity <= 0 then
      raise exception 'Invalid cart item';
    end if;

    select id, name, price, stock
      into v_product
      from public.products
     where id = v_item.product_id
       for update;

    if not found then
      raise exception 'A product in your cart is no longer available';
    end if;

    if v_product.stock < v_item.quantity then
      raise exception 'Not enough stock for "%": only % left',
        v_product.name, v_product.stock;
    end if;

    v_price := round(coalesce(v_product.price, 0)::numeric, 2);

    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_price, v_item.quantity);

    update public.products
       set stock = stock - v_item.quantity
     where id = v_product.id;

    v_total := v_total + v_price * v_item.quantity;
  end loop;

  update public.orders
     set total  = round(v_total, 2),
         status = 'done'
   where id = v_order_id;

  return jsonb_build_object('order_id', v_order_id, 'total', round(v_total, 2));
end;
$$;

revoke execute on function public.place_order(jsonb) from public, anon;
grant  execute on function public.place_order(jsonb) to authenticated;


