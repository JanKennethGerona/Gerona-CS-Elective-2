-- roles ---------------------------------------------------------------
create table public.roles (
  id          bigint generated by default as identity primary key,
  role        varchar     not null unique,
  created_at  timestamptz not null default now(),
  encoded_by  uuid        null references auth.users (id) on delete set null
);

-- profiles (1:1 with auth.users) -------------------------------------
create table public.profiles (
  id          uuid        primary key references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  email       text,
  firstname   text,
  lastname    text,
  role_id     bigint      references public.roles (id)
);

-- categories ----------------------------------------------------------
create table public.categories (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text        not null unique check (length(trim(name)) > 0)
);

-- products ------------------------------------------------------------
create table public.products (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  name         text        not null check (length(trim(name)) > 0),
  description  text,
  stock        int2        not null default 0 check (stock >= 0),
  image_url    text,
  category_id  bigint      not null references public.categories (id) on delete restrict,
  price        float4      check (price >= 0)
);

-- orders --------------------------------------------------------------
create table public.orders (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_id     uuid        references auth.users (id) on delete set null,
  status      text        default 'pending'
              check (status in ('pending','processing','done','shipped',
                                'delivered','cancelled','returned','refunded')),
  total       numeric     check (total >= 0)
);

-- order_items ---------------------------------------------------------
-- product_name = snapshot of the product name at checkout time, so a
-- customer's past orders still show the product name, quantity and price
-- even after the product is edited or removed from the catalog.
-- product_id becomes NULL (instead of blocking the delete) if the
-- product is later deleted by an admin.
create table public.order_items (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  order_id      bigint      not null references public.orders (id) on delete cascade,
  product_id    bigint      null references public.products (id) on delete set null,
  product_name  text        not null,
  unit_price    numeric     not null check (unit_price >= 0),
  quantity      bigint      not null check (quantity > 0)
);

create index on public.products    (category_id);
create index on public.orders      (user_id, created_at desc);
create index on public.order_items (order_id);


