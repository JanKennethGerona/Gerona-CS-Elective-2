-- ---------------------------------------------------------------------
-- 5. Column privileges (defence in depth on top of RLS)
-- ---------------------------------------------------------------------
-- profiles: users may only ever update first/last name
revoke update on public.profiles from anon, authenticated;
grant  update (firstname, lastname) on public.profiles to authenticated;

-- orders: admins may only ever update the status column
revoke update on public.orders from anon, authenticated;
grant  update (status) on public.orders to authenticated;

-- nobody inserts orders/order_items directly – only through place_order()
revoke insert, delete on public.orders      from anon, authenticated;
revoke insert, update, delete on public.order_items from anon, authenticated;


