-- profiles: customer = read & update own row (never the role); admin = read all
create policy "profiles read own" on public.profiles
  for select to authenticated
  using (id = auth.uid());

create policy "profiles admin read all" on public.profiles
  for select to authenticated
  using ((select public.is_admin()));

create policy "profiles update own" on public.profiles
  for update to authenticated
  using (id = auth.uid() and not (select public.is_admin()))
  with check (id = auth.uid());

-- roles: customer = read; admin = read
create policy "roles read" on public.roles
  for select to authenticated
  using (true);

-- categories: customer = read; admin = read, add, edit, delete
create policy "categories read" on public.categories
  for select to authenticated
  using (true);

create policy "create category" on public.categories
  for insert to authenticated
  with check ((select public.is_admin()));

create policy "update category" on public.categories
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "delete category" on public.categories
  for delete to authenticated
  using ((select public.is_admin()));

-- products: customer = read; admin = read, add, edit, delete
create policy "products read" on public.products
  for select to authenticated
  using (true);

create policy "create product" on public.products
  for insert to authenticated
  with check ((select public.is_admin()));

create policy "update product" on public.products
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "delete product" on public.products
  for delete to authenticated
  using ((select public.is_admin()));

-- orders: customer = read own only; admin = read all, update status
create policy "orders read own" on public.orders
  for select to authenticated
  using (user_id = auth.uid());

create policy "orders admin read all" on public.orders
  for select to authenticated
  using ((select public.is_admin()));

create policy "orders admin update status" on public.orders
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- order_items: customer = read items of own orders only; admin = read all
create policy "order_items read own" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = auth.uid()
  ));

create policy "order_items admin read all" on public.order_items
  for select to authenticated
  using ((select public.is_admin()));


